# Parallel encoding function for chunks
def encode_chunk(chunk, batch_size=1024):
    """Encode a chunk with optimal batch size for 12 cores."""
    return onnx_model.encode(
        chunk,
        batch_size=batch_size,
        show_progress_bar=False,
        convert_to_numpy=True
    )

# Strategy: Split into 4 chunks for parallel processing (system has 12 cores)
print("Encoding with parallel processing (4 workers × 3 cores each)...")
